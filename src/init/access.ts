/**
 * How agents reach the code index: the `devctx-code` Agent Skill (repository files every tool
 * discovers) plus pre-approval of its one command prefix in each tool's permission settings, so
 * running a skill command never stops for an approval prompt.
 */

export const SKILL_NAME = 'devctx-code';
/** Command prefix the skill tells agents to run (from the repository root). */
export const CODE_COMMAND = '.devctx/bin/devctx code';
const MARKER = 'devctx:generated';

type Json = Record<string, unknown>;

export interface AccessResult {
  file: string;
  action: 'created' | 'updated' | 'unchanged' | 'removed' | 'skipped';
  note?: string;
}

function obj(v: unknown): Json {
  return v && typeof v === 'object' && !Array.isArray(v) ? (v as Json) : {};
}

function strings(v: unknown): string[] {
  return Array.isArray(v) ? v.filter((x): x is string => typeof x === 'string') : [];
}

// ---- skill ----------------------------------------------------------------------------------

/**
 * Skill folders per tool. `.agents/skills` is read by Codex, Copilot (VS Code and CLI) and
 * Cursor; Claude Code reads `.claude/skills` (Copilot and Cursor read it too, so with both
 * present they list the same skill twice); Kiro reads `.kiro/skills`.
 */
function skillFiles(tools: readonly ToolId[]): { rel: string; claude: boolean }[] {
  const out: { rel: string; claude: boolean }[] = [];
  if (tools.includes('claude')) out.push({ rel: `.claude/skills/${SKILL_NAME}/SKILL.md`, claude: true });
  if (tools.some((t) => t === 'codex' || t === 'copilot' || t === 'cursor')) out.push({ rel: `.agents/skills/${SKILL_NAME}/SKILL.md`, claude: false });
  if (tools.includes('kiro')) out.push({ rel: `.kiro/skills/${SKILL_NAME}/SKILL.md`, claude: false });
  return out;
}

