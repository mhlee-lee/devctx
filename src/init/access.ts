// ---- per-machine permission files --------------------------------------------------------------

/** Copilot CLI keys saved approvals by the main repository root (linked worktrees share it). */
function mainRepoRoot(root: string): string {
  const r = git(['rev-parse', '--path-format=absolute', '--git-common-dir'], root, 5_000);
  if (r.ok && r.stdout && path.basename(r.stdout) === '.git') return path.dirname(r.stdout);
  return path.resolve(root);
}

const COPILOT_IDS = [`${CODE_COMMAND}:*`, `./${CODE_COMMAND}:*`];

/**
 * Copilot CLI reads saved approvals only from `~/.copilot/permissions-config.json`, keyed by
 * repository path (no repository-level file exists), so each machine gets its own entry.
 */
function copilotCliPermissions(root: string, enabled: boolean): AccessResult {
  const home = process.env.COPILOT_HOME ? path.resolve(process.env.COPILOT_HOME) : path.join(os.homedir(), '.copilot');
  const file = path.join(home, 'permissions-config.json');
  if (!fs.existsSync(home)) return { file, action: 'unchanged' };
  const key = mainRepoRoot(root);
  return editJson(
    root,
    file,
    (d) => {
      const locations = obj(d.locations);
      const loc = obj(locations[key]);
      const approvals = Array.isArray(loc.tool_approvals) ? (loc.tool_approvals as unknown[]).map(obj) : [];
      const has = approvals.some((a) => a.kind === 'commands' && COPILOT_IDS.every((id) => strings(a.commandIdentifiers).includes(id)));
      if (enabled === has) return;
      const next = enabled
        ? [...approvals, { kind: 'commands', commandIdentifiers: [...COPILOT_IDS] }]
        : approvals
            .map((a) => (a.kind === 'commands' ? { ...a, commandIdentifiers: strings(a.commandIdentifiers).filter((id) => !COPILOT_IDS.includes(id)) } : a))
            .filter((a) => a.kind !== 'commands' || strings(a.commandIdentifiers).length > 0);
      if (next.length > 0) loc.tool_approvals = next;
      else delete loc.tool_approvals;
      if (Object.keys(loc).length > 0) locations[key] = loc;
      else delete locations[key];
      if (Object.keys(locations).length > 0) d.locations = locations;
      else delete d.locations;
    },
    { create: enabled, absolute: true },
  );
}

const KIRO_MATCH = [`${CODE_COMMAND} *`, `./${CODE_COMMAND} *`];

/**
 * Kiro keeps workspace permission rules outside the repository, in
 * `~/.kiro/workspace-roots/<first 16 hex of sha256(workspace path)>/permissions.yaml`.
 */
export function kiroPermissionsFile(root: string): string {
  const home = process.env.KIRO_HOME ? path.resolve(process.env.KIRO_HOME) : path.join(os.homedir(), '.kiro');
  return path.join(home, 'workspace-roots', sha256(path.resolve(root)).slice(0, 16), 'permissions.yaml');
}

function kiroPermissions(root: string, enabled: boolean): AccessResult {
  const file = kiroPermissionsFile(root);
  const home = path.dirname(path.dirname(path.dirname(file)));
  if (!fs.existsSync(home)) return { file, action: 'unchanged' };
  const text = readText(file);
  if (text === null && !enabled) return { file, action: 'unchanged' };
  const doc = parseDocument(text ?? 'rules: []\n');
  if (doc.errors.length > 0) return { file, action: 'skipped', note: 'not valid YAML; left untouched' };
  let rules = doc.get('rules');
  if (!isSeq(rules)) {
    doc.set('rules', doc.createNode([]));
    rules = doc.get('rules');
  }
  if (!isSeq(rules)) return { file, action: 'skipped', note: 'unexpected layout' };
  const ours = (item: unknown): boolean => {
    if (!isMap(item)) return false;
    const match = item.get('match');
    const list = isSeq(match) ? match.items.map((m) => String((m as { value?: unknown }).value ?? m)) : [];
    return item.get('capability') === 'shell' && item.get('effect') === 'allow' && KIRO_MATCH.every((m) => list.includes(m));
  };
  const present = rules.items.some(ours);
  if (enabled === present) return { file, action: 'unchanged' };
  if (enabled) {
    const rule = doc.createNode({ capability: 'shell', effect: 'allow', match: [...KIRO_MATCH] });
    rules.flow = false; // the block style Kiro itself writes
    rules.add(rule);
  } else rules.items = rules.items.filter((i) => !ours(i));
  const empty = rules.items.length === 0 && isMap(doc.contents) && doc.contents.items.length === 1;
  if (empty) {
    fs.rmSync(file, { force: true });
    try {
      fs.rmdirSync(path.dirname(file)); // the workspace folder, when devctx created it
    } catch {
      // Kiro keeps other state there
    }
    return { file, action: 'removed' };
  }
  writeFileAtomic(file, String(doc));
  return { file, action: enabled ? (text === null ? 'created' : 'updated') : 'removed' };
}

// ---- entry points ------------------------------------------------------------------------------

export interface AccessOptions {
  /** Code index on: skills are installed; off: removed. */
  enabled: boolean;
  /** Also pre-approve the command (config `code_index.preapprove`). */
  preapprove: boolean;
  language: Language;
}

/** Repository files: skills and the permission settings tools read from the repository. */
export function installRepoAccess(root: string, tools: readonly ToolId[], opts: AccessOptions): AccessResult[] {
  const wanted = new Map(skillFiles(opts.enabled ? tools : []).map((s) => [s.rel, renderSkill(opts.language, s.claude)]));
  const results = ALL_SKILL_FILES.map((rel) => writeOwned(root, rel, wanted.get(rel) ?? null));
  const allow = opts.enabled && opts.preapprove;
  const has = (t: ToolId): boolean => allow && tools.includes(t);
  results.push(claudeSettings(root, has('claude')));
  results.push(writeOwned(root, '.codex/rules/devctx.rules', has('codex') ? codexRules() : null));
  results.push(vscodeSettings(root, has('copilot')));
  results.push(cursorPermissions(root, has('cursor')));
  results.push(cursorCli(root, has('cursor')));
  return results;
}

/**
 * Per-machine permission files (Copilot CLI, Kiro): written by `devctx init` and re-checked at
 * session start, so a teammate's clone gets them without running anything.
 */
export function installMachineAccess(root: string, tools: readonly ToolId[], opts: AccessOptions): AccessResult[] {
  const allow = opts.enabled && opts.preapprove;
  const results: AccessResult[] = [];
  if (tools.includes('copilot') || !allow) results.push(copilotCliPermissions(root, allow && tools.includes('copilot')));
  if (tools.includes('kiro') || !allow) results.push(kiroPermissions(root, allow && tools.includes('kiro')));
  return results;
}

export function installAgentAccess(root: string, tools: readonly ToolId[], opts: AccessOptions): AccessResult[] {
  return [...installRepoAccess(root, tools, opts), ...installMachineAccess(root, tools, opts)];
}

/**
 * Why init could not add devctx's entry to a JSON settings file, and what to add by hand: devctx
 * never rewrites a file with comments (they would be lost), so running init again does not help.
 */
function jsonHint(file: string, mutate: (d: Json) => void, ok: boolean): string | undefined {
  const text = ok ? null : readText(file);
  if (text === null) return undefined;
  try {
    JSON.parse(text);
    return undefined;
  } catch {
    // comments or broken
  }
  try {
    JSON.parse(stripJsonc(text));
  } catch {
    return 'not valid JSON: fix it, then run "devctx init"';
  }
  const want: Json = {};
  mutate(want);
  return `has comments, so devctx does not rewrite it ("devctx init" will not help). Merge this in by hand: ${JSON.stringify(want)}`;
}

export interface AccessStatus {
  file: string;
  ok: boolean;
  /** What to do when the fix is not "run devctx init". */
  hint?: string;
}

/** What `devctx doctor` / `devctx code status` report: expected files and whether they are in place. */
export function agentAccessStatus(root: string, tools: readonly ToolId[], opts: AccessOptions): AccessStatus[] {
  if (!opts.enabled) return [];
  const out: AccessStatus[] = skillFiles(tools).map((s) => ({ file: s.rel, ok: readText(path.join(root, s.rel)) === renderSkill(opts.language, s.claude) }));
  if (!opts.preapprove) return out;
  const contains = (file: string, needle: string): boolean => (readText(file) ?? '').includes(needle);
  const json = (rel: string, needle: string, mutate: (d: Json) => void): AccessStatus => {
    const file = path.join(root, rel);
    const ok = contains(file, needle);
    const hint = jsonHint(file, mutate, ok);
    return hint ? { file: rel, ok, hint } : { file: rel, ok };
  };
  if (tools.includes('claude')) out.push(json('.claude/settings.json', CLAUDE_RULES[0] as string, claudeEdit(true)));
  if (tools.includes('codex')) out.push({ file: '.codex/rules/devctx.rules', ok: readText(path.join(root, '.codex/rules/devctx.rules')) === codexRules() });
  if (tools.includes('copilot')) out.push(json('.vscode/settings.json', 'devctx/bin/devctx code', vscodeEdit(true)));
  if (tools.includes('cursor')) out.push(json('.cursor/permissions.json', CODE_COMMAND, cursorEdit(true, cursorUserAllowlist())));
  if (tools.includes('kiro') && fs.existsSync(path.dirname(path.dirname(path.dirname(kiroPermissionsFile(root)))))) {
    out.push({ file: '~/.kiro/workspace-roots/…/permissions.yaml', ok: contains(kiroPermissionsFile(root), KIRO_MATCH[0] as string) });
  }
  return out;
}

// ---- the MCP server devctx registered before the skill ---------------------------------------------

const LEGACY_SERVER = 'devctx-code';
const TOML_BEGIN = '# >>> devctx >>>';
const TOML_END = '# <<< devctx <<<';

/** Removes the `devctx-code` MCP server earlier versions registered (every tool's project file). */
export function removeLegacyMcp(root: string): AccessResult[] {
  const results: AccessResult[] = [];
  for (const [rel, key] of [
    ['.mcp.json', 'mcpServers'],
    ['.vscode/mcp.json', 'servers'],
    ['.cursor/mcp.json', 'mcpServers'],
    ['.kiro/settings/mcp.json', 'mcpServers'],
  ] as const) {
    results.push(
      editJson(
        root,
        rel,
        (d) => {
          const servers = obj(d[key]);
          if (!(LEGACY_SERVER in servers)) return;
          delete servers[LEGACY_SERVER];
          d[key] = servers;
          if (Object.keys(servers).length === 0) delete d[key];
        },
        { create: false },
      ),
    );
  }
  const rel = '.codex/config.toml';
  const file = path.join(root, rel);
  const text = readText(file);
  const start = text?.indexOf(TOML_BEGIN) ?? -1;
  const end = text?.indexOf(TOML_END) ?? -1;
  if (text !== null && start >= 0 && end > start && text.slice(start, end).includes(`mcp_servers.${LEGACY_SERVER}`)) {
    const rest = `${text.slice(0, start)}${text.slice(end + TOML_END.length)}`.replace(/\n{3,}/g, '\n\n').trim();
    if (rest) writeFileAtomic(file, `${rest}\n`);
    else fs.rmSync(file, { force: true });
    results.push({ file: rel, action: 'removed' });
  }
  return results
    .filter((r) => r.action !== 'unchanged')
    .map((r) => (r.action === 'skipped' ? r : { ...r, note: 'removed the devctx-code MCP server (replaced by the skill)' }));
}
