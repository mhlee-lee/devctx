function writeOwned(root: string, rel: string, content: string | null): AccessResult {
  const file = path.join(root, rel);
  const current = readText(file);
  if (content === null) {
    if (current === null) return { file: rel, action: 'unchanged' };
    if (!current.includes(MARKER)) return { file: rel, action: 'skipped', note: 'not written by devctx; left in place' };
    fs.rmSync(file, { force: true });
    try {
      fs.rmdirSync(path.dirname(file)); // only when empty
    } catch {
      // other files in the skill folder
    }
    return { file: rel, action: 'removed' };
  }
  if (current === content) return { file: rel, action: 'unchanged' };
  if (current !== null && !current.includes(MARKER)) return { file: rel, action: 'skipped', note: 'a file devctx did not write is in the way' };
  writeFileAtomic(file, content);
  return { file: rel, action: current === null ? 'created' : 'updated' };
}

// ---- JSON settings files ---------------------------------------------------------------------

/** JSON with comments and trailing commas (VS Code and Cursor settings) to plain JSON text. */
function stripJsonc(text: string): string {
  return text
    .replace(/("(?:[^"\\]|\\.)*")|\/\/[^\n]*|\/\*[\s\S]*?\*\//g, (_m, s: string | undefined) => s ?? '')
    .replace(/,(\s*[}\]])/g, '$1');
}

/**
 * Edits a JSON settings file in place, keeping every other key. Files with comments are left
 * alone (rewriting would drop them) unless they already contain what devctx wants.
 */
function editJson(root: string, rel: string, mutate: (data: Json) => void, opts: { create: boolean; absolute?: boolean }): AccessResult {
  const file = opts.absolute ? rel : path.join(root, rel);
  const text = readText(file);
  let data: Json = {};
  if (text === null) {
    if (!opts.create) return { file: rel, action: 'unchanged' };
  } else {
    try {
      const parsed: unknown = JSON.parse(text);
      if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) return { file: rel, action: 'skipped', note: 'not a JSON object; left untouched' };
      data = parsed as Json;
    } catch {
      let loose: Json | null = null;
      try {
        loose = obj(JSON.parse(stripJsonc(text)));
      } catch {
        return { file: rel, action: 'skipped', note: 'not valid JSON; left untouched' };
      }
      const before = JSON.stringify(loose);
      mutate(loose);
      if (JSON.stringify(loose) === before) return { file: rel, action: 'unchanged' };
      return { file: rel, action: 'skipped', note: 'has comments; add the devctx entry by hand (see "devctx code status")' };
    }
  }
  const before = JSON.stringify(data);
  mutate(data);
  if (JSON.stringify(data) === before) return { file: rel, action: 'unchanged' };
  if (Object.keys(data).length === 0) {
    fs.rmSync(file, { force: true });
    return { file: rel, action: 'removed' };
  }
  writeFileAtomic(file, `${JSON.stringify(data, null, 2)}\n`);
  return { file: rel, action: text === null ? 'created' : 'updated' };
}

/** Adds (or removes) `values` in the string array at `holder[key]`, dropping the key when empty. */
function setStrings(holder: Json, key: string, values: readonly string[], enabled: boolean): void {
  const list = strings(holder[key]);
  const next = enabled ? [...list, ...values.filter((v) => !list.includes(v))] : list.filter((v) => !values.includes(v));
  if (next.length === 0) delete holder[key];
  else if (next.length !== list.length || !Array.isArray(holder[key])) holder[key] = next;
}

function nested(data: Json, key: string): Json {
  const value = obj(data[key]);
  data[key] = value;
  return value;
}

function dropEmpty(data: Json, key: string): void {
  if (Object.keys(obj(data[key])).length === 0) delete data[key];
}

const CLAUDE_RULES = [`Bash(${CODE_COMMAND} *)`, `Bash(./${CODE_COMMAND} *)`];

/** Claude Code: project `.claude/settings.json` permission rules (the hooks live in the same file). */
const claudeEdit =
  (enabled: boolean) =>
  (d: Json): void => {
    const perms = nested(d, 'permissions');
    setStrings(perms, 'allow', CLAUDE_RULES, enabled);
    dropEmpty(d, 'permissions');
  };

function claudeSettings(root: string, enabled: boolean): AccessResult {
  return editJson(root, '.claude/settings.json', claudeEdit(enabled), { create: enabled });
}

const VSCODE_KEY = 'chat.tools.terminal.autoApprove';
const VSCODE_RULE = '/^(\\./)?\\.devctx/bin/devctx code(\\s|$)/';

/** Copilot in VS Code: terminal auto-approval rules in the workspace settings (trusted workspaces). */
const vscodeEdit =
  (enabled: boolean) =>
  (d: Json): void => {
    const rules = nested(d, VSCODE_KEY);
    if (enabled) rules[VSCODE_RULE] = true;
    else delete rules[VSCODE_RULE];
    dropEmpty(d, VSCODE_KEY);
  };

function vscodeSettings(root: string, enabled: boolean): AccessResult {
  return editJson(root, '.vscode/settings.json', vscodeEdit(enabled), { create: enabled });
}

const CURSOR_INSTRUCTION = `Commands that start with \`${CODE_COMMAND}\` are read-only queries of this repository's code index (search_symbols, get_symbol, trace_calls, file_outline, repo_overview, change_impact, search_text); allow them.`;

function cursorUserAllowlist(): boolean {
  const text = readText(path.join(os.homedir(), '.cursor', 'permissions.json'));
  if (!text) return false;
  try {
    return Array.isArray(obj(JSON.parse(stripJsonc(text))).terminalAllowlist);
  } catch {
    return false;
  }
}

/**
 * Cursor IDE: `.cursor/permissions.json`. A `terminalAllowlist` there replaces each user's own
 * in-app allowlist, so devctx only appends to one that is already file-controlled; otherwise it
 * steers the Auto-review classifier, which merges with personal settings.
 */
const cursorEdit =
  (enabled: boolean, userList: boolean) =>
  (d: Json): void => {
    if (Array.isArray(d.terminalAllowlist) || (userList && enabled)) setStrings(d, 'terminalAllowlist', [CODE_COMMAND], enabled);
    const auto = nested(d, 'autoRun');
    setStrings(auto, 'allow_instructions', [CURSOR_INSTRUCTION], enabled);
    dropEmpty(d, 'autoRun');
  };

function cursorPermissions(root: string, enabled: boolean): AccessResult {
  return editJson(root, '.cursor/permissions.json', cursorEdit(enabled, cursorUserAllowlist()), { create: enabled });
}

/** Cursor CLI: `.cursor/cli.json` shadows the global CLI config, so it is only extended, never created. */
function cursorCli(root: string, enabled: boolean): AccessResult {
  return editJson(
    root,
    '.cursor/cli.json',
    (d) => {
      const perms = nested(d, 'permissions');
      setStrings(perms, 'allow', [`Shell(${CODE_COMMAND.replace(' ', ':')} *)`], enabled);
      dropEmpty(d, 'permissions');
    },
    { create: false },
  );
}

